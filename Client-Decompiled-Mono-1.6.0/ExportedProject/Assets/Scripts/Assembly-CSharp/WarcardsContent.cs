	public void BuyCardPack(CardPackRecord IHFNCPHJHCK)
	{
		NGNPIOOAHEH typePack = IHFNCPHJHCK.typePack;
		int num = Singleton<GameVariables>.instance.CardPackWarbucks(typePack);
		int num2 = Singleton<GameVariables>.instance.CardPackGold(typePack);
		float value = Singleton<GameVariables>.instance.PriceOfPack(typePack).Value1;
		switch (typePack)
		{
		case NGNPIOOAHEH.Starter:
			Singleton<BeanstalkServerManager>.instance.BuyPack(Singleton<GameVariables>.instance.PackId(NGNPIOOAHEH.Starter));
			Debug.Log("STARTER PACK for $" + value.ToString("0.##"));
			break;
		case NGNPIOOAHEH.Value:
			Singleton<BeanstalkServerManager>.instance.BuyPack(Singleton<GameVariables>.instance.PackId(NGNPIOOAHEH.Value));
			Debug.Log("VALUE PACK for $" + value.ToString("0.##"));
			break;
		case NGNPIOOAHEH.Bronze:
		case NGNPIOOAHEH.Silver:
		case NGNPIOOAHEH.Gold:
		{
			if (IHFNCPHJHCK == null)
			{
				break;
			}
			int num3 = Singleton<OfferManager>.instance.DiscountedCardpack(typePack);
			num = num * (100 - num3) / 100;
			num2 = num2 * (100 - num3) / 100;
			if (!Singleton<Wallet>.instance.CanBuyW(num))
			{
				GuiElementSingle<NotEnoughDialog>.instance.ShowWarbucks(num, Localization.Localize(typePack.ToString().ToUpper() + "PACK"));
				GuiElementSingle<InappScreen>.instance.GIJGFEOICHF = "WarCards";
				break;
			}
			if (!Singleton<Wallet>.instance.CanBuyGold(num2))
			{
				GuiElementSingle<NotEnoughDialog>.instance.ShowGold(num2, Localization.Localize(typePack.ToString().ToUpper() + "PACK"));
				GuiElementSingle<InappScreen>.instance.GIJGFEOICHF = "WarCards";
				break;
			}
			if (num > 0)
			{
				Singleton<Wallet>.instance.CDIDDJGINID(num);
			}
			if (num2 > 0)
			{
				Singleton<Wallet>.instance.MBAFMBJFOKH(num2);
			}
			GuiScreenSingle<CardMenuScreen>.instance.AAPOFJBNMHM.StartShowAnimation(CardManager.instance.BuyCardPack(typePack, num, num2, num3));
			IHFNCPHJHCK.PlayBuyAnimation(GuiScreenSingle<CardMenuScreen>.instance.AAPOFJBNMHM.transform);
			break;
		}
		default:
			Singleton<EventTrackingManager>.instance.ICDALIJKFMH(MHNMOFPPKBN.RandomCard);
			KOPABJFLKLO[0].SetVideoRewardPack(false);
			break;
		}
	}

