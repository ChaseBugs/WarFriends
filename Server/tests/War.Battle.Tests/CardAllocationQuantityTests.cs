using System.Numerics;
using System.Text.Json;
using System.Text.Json.Nodes;
using MongoDB.Driver;
using War.BattleServer;
using War.Persistence;
using War.Protocol;
using War.Shared;

/// <summary>Checks owned quantities without converting duplicate inventory into extra hand uses.</summary>
internal static class CardAllocationQuantityTests
{
    private const string CardId = "SLOWDOWN";
    private const string CardClassId = "CardSlowdown";
    private const int OwnedCopies = 3;
    private const float EffectSeconds = 10;

    /// <summary>Verifies quantity validation, transport, immutable snapshots and host consumption.</summary>
    public static int Run(MatchManifest definition)
    {
        string firstPlayer = definition.Players[0].PlayerId;
        string secondPlayer = definition.Players[1].PlayerId;
        CheckFrozenQuantities(firstPlayer);
        CheckInvalidQuantities(firstPlayer);
        CheckWireQuantities(firstPlayer);
        CheckHostConsumption(definition, firstPlayer, secondPlayer);
        return 4;
    }

    /// <summary>Verifies durable quantities and missing-authority rejection using an owned temporary database.</summary>
    public static async Task RunMongoAsync(string connectionString)
    {
        string databaseName = "war_card_quantities_" + Guid.NewGuid().ToString("N");
        var mongo = new MongoClient(connectionString);
        var store = new BattleAllocationStore(connectionString, databaseName);
        string playerId = Guid.NewGuid().ToString("N");
        try
        {
            await store.Initialize(CancellationToken.None);
            await store.Put(Allocation(playerId, OwnedCopies), CancellationToken.None);
            BattleAllocationProjection? single = await store.Get(playerId, CancellationToken.None);
            IReadOnlyList<BattleAllocationProjection> batch = await store.GetMany([playerId], CancellationToken.None);
            Require(single?.CardCounts.Single() == OwnedCopies && batch.Single().CardCounts.Single() == OwnedCopies,
                "Mongo allocation reads lost the durable quantity.");

            var collection = mongo.GetDatabase(databaseName)
                .GetCollection<BattleAllocationDocument>("battle_allocations");
            await collection.UpdateOneAsync(row => row.PlayerId == playerId,
                Builders<BattleAllocationDocument>.Update.Unset(row => row.CardCounts));
            await RejectAsync(async () => { await store.Get(playerId, CancellationToken.None); });
            await RejectAsync(async () => { await store.GetMany([playerId], CancellationToken.None); });
            string[] fullCatalog = OrdinaryCardIdentityCatalog.All.ToArray();
            await store.Put(CardCatalogCapacityTests.CreateAllocation(playerId, fullCatalog), CancellationToken.None);
            single = await store.Get(playerId, CancellationToken.None);
            batch = await store.GetMany([playerId], CancellationToken.None);
            Require(single!.CardIds.SequenceEqual(fullCatalog) &&
                batch.Single().CardIds.SequenceEqual(fullCatalog) &&
                single.CardCounts.Count == fullCatalog.Length && single.CardCounts.All(count => count == 1) &&
                batch.Single().CardCounts.SequenceEqual(single.CardCounts),
                "Mongo truncated the full source card catalog or lost its quantities.");
            await BattleAllocationSourceTests.RunMongoAsync(connectionString, databaseName);
            await BattleAllocationPreparationTests.RunMongoAsync(connectionString, databaseName);
            await BattleAllocationPreparationRaceTests.RunMongoAsync(connectionString, databaseName);
            await CardPackConcurrencyTests.RunAsync(connectionString, databaseName);
            Console.WriteLine("PASS: Mongo full card catalog and quantities round-trip; " +
                "missing quantity authority rejected by both reads");
        }
        finally
        {
            // This name is generated by the test, never supplied by the caller.
            await mongo.DropDatabaseAsync(databaseName);
        }
    }

    private static BattleAllocationProjection Allocation(string playerId, int count)
    {
        return new BattleAllocationProjection(playerId, [CardId], [], [], [], [])
        {
            CardCounts = [count]
        };
    }

    private static void CheckFrozenQuantities(string playerId)
    {
        int[] counts = [OwnedCopies];
        var input = Allocation(playerId, OwnedCopies);
        input.CardCounts = counts;
        BattleAllocationProjection frozen = BattleAllocationProjection.Validate(input);

        counts[0] = 1;
        Require(frozen.CardCounts.Single() == OwnedCopies, "Allocation retained mutable quantities.");
        Require(BattleAllocationProjection.Validate(Allocation(playerId, int.MaxValue))
            .CardCounts.Single() == int.MaxValue, "A valid client-width quantity was truncated.");
    }

    private static void CheckInvalidQuantities(string playerId)
    {
        foreach (int[] counts in new[] { Array.Empty<int>(), new[] { 0 }, new[] { -1 }, new[] { 1, 2 } })
        {
            var allocation = Allocation(playerId, OwnedCopies);
            allocation.CardCounts = counts;
            Reject(() => BattleAllocationProjection.Validate(allocation));
        }
        var missing = Allocation(playerId, OwnedCopies);
        missing.CardCounts = null!;
        Reject(() => BattleAllocationProjection.Validate(missing));
        var empty = new BattleAllocationProjection(playerId, [], [], [], [], []);
        Require(BattleAllocationProjection.Validate(empty).CardCounts.Count == 0,
            "Empty inventory no longer admits without granting cards.");
    }

    private static void CheckWireQuantities(string playerId)
    {
        string json = JsonSerializer.Serialize(Allocation(playerId, OwnedCopies));
        BattleAllocationProjection restored = JsonSerializer.Deserialize<BattleAllocationProjection>(json)!;
        Require(BattleAllocationProjection.Validate(restored).CardCounts.Single() == OwnedCopies,
            "Manifest transport lost the durable quantity.");

        JsonObject missing = JsonNode.Parse(json)!.AsObject();
        missing.Remove("CardCounts");
        Reject(() => BattleAllocationProjection.Validate(
            JsonSerializer.Deserialize<BattleAllocationProjection>(missing.ToJsonString())!));
    }

    private static void CheckHostConsumption(MatchManifest definition, string firstPlayer, string secondPlayer)
    {
        var host = new MatchEngine(definition);
        host.ConfigureBattleAllocations([Allocation(firstPlayer, OwnedCopies), Allocation(secondPlayer, 1)]);
        Require(host.Admit(firstPlayer) && host.Admit(secondPlayer), "Card quantity fixture admission failed.");
        foreach (string playerId in new[] { firstPlayer, secondPlayer })
        {
            host.Command(playerId, new MatchCommand
            {
                CommandId = 1,
                Ready = new ReadyCommand { ManifestHash = host.ManifestHash }
            });
        }
        Require(host.Snapshot().Phase == BattlePhase.Countdown, "Card quantity fixture did not reach countdown.");

        var request = new WarCardEffectRequest(CardClassId, Vector3.Zero, EffectSeconds, 0);
        string receipt = Guid.NewGuid().ToString("N");
        Require(host.TryApplyCardEffect(receipt, firstPlayer, request), "The owned hand card was unavailable.");
        Require(!host.TryApplyCardEffect(receipt, firstPlayer, request), "Card receipt replay consumed twice.");
        ulong revision = host.Snapshot().StateRevision;
        Require(!host.TryApplyCardEffect(Guid.NewGuid().ToString("N"), firstPlayer, request) &&
            host.Snapshot().StateRevision == revision, "Duplicate inventory granted another use of the same hand card.");
        Require(host.TryApplyCardEffect(Guid.NewGuid().ToString("N"), secondPlayer, request),
            "One player's spending consumed the other player's inventory.");
    }

    private static void Reject(Action action)
    {
        try
        {
            action();
        }
        catch (InvalidDataException)
        {
            return;
        }
        throw new InvalidOperationException("Invalid card quantity authority was accepted.");
    }

    private static async Task RejectAsync(Func<Task> action)
    {
        try
        {
            await action();
        }
        catch (InvalidDataException)
        {
            return;
        }
        throw new InvalidOperationException("Missing durable card quantities were accepted.");
    }

    private static void Require(bool condition, string message)
    {
        if (!condition)
        {
            throw new InvalidOperationException(message);
        }
    }
}
